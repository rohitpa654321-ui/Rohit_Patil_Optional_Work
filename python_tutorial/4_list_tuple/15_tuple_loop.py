# using for loop
thistuple = ("apple","banana","cherry")
for x in thistuple :
    print(x)
print("\n")

# indexes
for i in range(len(thistuple)):
    print(thistuple[i])
print("\n")

# while loop
thistuple = ("apple","banana","cherry")
i = 0
while i < len(thistuple):
 print(thistuple[i])
 i = i+1
print("\n")